export function getLocalizedOrganName(organId: string, lang: Language, nameEn?: string, nameHi?: string): string {
  const organMap = ORGAN_LOCALIZATIONS[organId];
  if (organMap && organMap[lang]) {
    return organMap[lang]!;
  }
  if (lang === "hi" && nameHi) return nameHi;
  return nameEn || "";
}

export function getLocalizedSymptomName(symptomId: string, lang: Language, nameEn?: string, nameHi?: string): string {
  const symptomMap = SYMPTOM_LOCALIZATIONS[symptomId];
  if (symptomMap && symptomMap[lang]) {
    return symptomMap[lang]!;
  }
  if (lang === "hi" && nameHi) return nameHi;
  return nameEn || "";
}

export function getLocalizedColloquialRegion(
  regionId: BodyRegionId,
  lang: Language,
  colloquialEn?: string,
  colloquialHi?: string
): string {
  const regionMap = COLLOQUIAL_REGION_LOCALIZATIONS[regionId];
  if (regionMap && regionMap[lang]) {
    return regionMap[lang]!;
  }
  if (lang === "en") return colloquialEn || "";
  return colloquialHi || colloquialEn || "";
}

