export function getLocalizedGender(gender: string, t: TranslationDictionary): string {
  if (!gender) return "";
  const g = gender.trim().toLowerCase();
  if (g.startsWith("m") || g === "male") return t.male;
  if (g.startsWith("f") || g === "female") return t.female;
  return t.other;
}

